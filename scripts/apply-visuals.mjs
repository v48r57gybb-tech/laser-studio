import {readFile,writeFile,copyFile} from 'node:fs/promises';
import {Script} from 'node:vm';
const updates=[];
function once(text,before,after){if(text.split(before).length!==2)throw Error('Aggiornamento visuale: riferimento non univoco '+before);return text.replace(before,after);}
let probe=await readFile('dist/probe.js','utf8');
probe=once(probe,"form.addEventListener('submit',()=>{","form.addEventListener('cnc:before-display',()=>{");
new Script(probe);updates.push(['probe.js',probe]);
let demo=await readFile('dist/generation-demo.js','utf8');
demo=once(demo,'   const iso=output.value;if(!iso.trim())',"   form.dispatchEvent(new Event('cnc:before-display'));\n   const iso=output.value;if(!iso.trim())");
new Script(demo);updates.push(['generation-demo.js',demo]);
let sim=await readFile('dist/cnc-simulator.js','utf8');
const start=sim.indexOf('   if(op.tool===\'probe\'){ctx.fillRect'),end=sim.indexOf('   status.textContent=',start);
if(start<0||end<=start)throw Error('Rendering utensili non riconosciuto');
sim=sim.slice(0,start)+"   root.CncVisual.drawTool(ctx,p,op.tool,screen,zoom,performance.now()/1000);\n"+sim.slice(end);
sim=once(sim,'   ctx.clearRect(0,0,canvas.clientWidth,canvas.clientHeight);',"   ctx.fillStyle='#031627';ctx.fillRect(0,0,canvas.clientWidth,canvas.clientHeight);");
sim=once(sim,'   seek.value=String((index+progress)/ops.length);',"   ctx.fillStyle='#eaf4fc';ctx.font='12px monospace';ctx.fillText(op.toolName+' | Riga '+op.line+' | Z '+p.z.toFixed(3),12,canvas.clientHeight-28);ctx.fillText('ANTEPRIMA NOMINALE - UTENSILI ILLUSTRATIVI NON DIMENSIONALI',12,canvas.clientHeight-10);\n   seek.value=String((index+progress)/ops.length);");
sim=once(sim,'  simBtn.onclick=()=>{',"  root.CncVisual.attachRecording({container,canvas,restart(){index=0;progress=0;playing=true;render();},finished:()=>ops.length>0&&index===ops.length-1&&progress===1});\n  simBtn.onclick=()=>{");
sim=once(sim,'(h-100)/Math.max(1,hiY-loY)','(h-180)/Math.max(1,hiY-loY)');
sim=once(sim,'panY=h/2-(loY+hiY)/2*zoom;','panY=h/2+35-(loY+hiY)/2*zoom;');
new Script(sim);updates.push(['cnc-simulator.js',sim]);
let html=await readFile('dist/index.html','utf8');
const tag='<script src="cnc-simulator.js"></script>';
if(!html.includes(tag))throw Error('Script simulatore mancante');
html=html.split(tag).join('');
html=once(html,'</body>','<script src="simulation-visuals.js"></script>\n'+tag+'\n</body>');updates.push(['index.html',html]);
new Script(await readFile('simulation-visuals.js','utf8'));
await copyFile('simulation-visuals.js','dist/simulation-visuals.js');
for(const [file,text] of updates)await writeFile('dist/'+file,text);
console.log('Tastatura inserita prima della presentazione ISO; utensili volumetrici e registrazione integrati.');
